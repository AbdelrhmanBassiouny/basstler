#!/usr/bin/env python3
"""
The plan hub: one page over every repository whose personal-notes branch holds plans.

Each repository keeps its own plans; the hub file names the hub page, the registry
repository whose copy lists every repository, and that list. Every repository's notes
carry a copy, so a session anywhere finds the hub page without reading another
repository, and any account reuses the same page instead of publishing a second one.

Subcommands:
    register --hub <hub.yaml> --repository <owner/repo> [--registry <owner/repo>] --output <out>
        Add a repository to the hub file, creating it (with this repository as its own
        registry, unless one is named) when absent.
    set-url --hub <hub.yaml> --url <artifact url> --output <out>
        Record the hub page's URL. Refuses to replace a different URL already recorded.
    gather --hub <hub.yaml> --output <repositories.json> [--remote-url-template <template>]
        Read every listed repository's plans and dashboard URLs off its notes branch, as
        build_hub.py's input.

``register`` and ``set-url`` print ``{"changed": true|false}``; push the output only when
it changed.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any

import yaml

from basstler.standard_streams import StandardStreamHandler

logger = StandardStreamHandler.logger_for(__name__)
"""
This module's logger, which is also what its command prints through.
"""


class HubDefault(Enum):
    """
    The values a hub file falls back to where it names none.
    """

    NOTES_BRANCH = "claude/personal-notes"
    """
    The branch every listed repository keeps its notes on.
    """

    PLANS_DIRECTORY = ".claude/personal/plans"
    """
    Where a notes branch keeps its plans.
    """

    DASHBOARD_URL_CACHE = "_generated/dashboard-urls.yaml"
    """
    The dashboard-URL cache, relative to the plans directory.
    """

    INDEX_KEY = "_index"
    """
    The cache key a repository's own index page is recorded under.
    """

    REMOTE_URL_TEMPLATE = "https://github.com/{repository}"
    """
    How a listed repository's name becomes a URL git can fetch.
    """


HUB_FILE_HEADER = """\
# The plan hub: one page listing every repository's plans. Generated by
# basstler.plan_hub - every listed repository's notes carry a copy, and the
# registry's copy is the one whose list is complete. Publish the hub page only
# to `url`; another account needs edit access to it, never a second page.
"""
"""
The comment every written hub file opens with.
"""


@dataclass
class PlanHub:
    """
    The hub file's content.
    """

    registry: str
    """
    The repository whose notes hold the complete list.
    """

    repositories: list[str] = field(default_factory=list)
    """
    Every repository whose plans the hub lists, in the order they are shown.
    """

    url: str | None = None
    """
    The hub page's Artifact URL, or ``None`` before it was first published.
    """

    notes_branch: str = HubDefault.NOTES_BRANCH.value
    """
    The branch each listed repository keeps its notes on.
    """

    @classmethod
    def from_mapping(cls, data: dict[str, Any]) -> PlanHub:
        """
        :param data: The parsed hub file.
        :return: The hub it describes.
        """
        return cls(
            registry=data["registry"],
            repositories=list(data.get("repositories") or []),
            url=data.get("url"),
            notes_branch=data.get("notes_branch") or HubDefault.NOTES_BRANCH.value,
        )

    @classmethod
    def load(cls, path: Path) -> PlanHub | None:
        """
        :param path: The hub file, which may not exist.
        :return: The hub, or ``None`` when the file is absent or empty.
        """
        if not path.is_file():
            return None
        data = yaml.safe_load(path.read_text())
        return cls.from_mapping(data) if data else None

    def to_text(self) -> str:
        """
        :return: The hub file's content, header comment first.
        """
        data = {
            "url": self.url,
            "registry": self.registry,
            "notes_branch": self.notes_branch,
            "repositories": self.repositories,
        }
        return HUB_FILE_HEADER + yaml.safe_dump(data, sort_keys=False)

    def register(self, repository: str) -> bool:
        """
        :param repository: The repository to list.
        :return: Whether it was not listed before.
        """
        if repository in self.repositories:
            return False
        self.repositories.append(repository)
        return True


@dataclass
class HubUrlConflictError(Exception):
    """
    Raised when a hub page URL would replace a different one already recorded.
    """

    recorded_url: str
    """
    The URL the hub file already names.
    """

    new_url: str
    """
    The URL that would have replaced it.
    """

    def __str__(self) -> str:
        return (
            f"The hub already lives at {self.recorded_url}; refusing to record "
            f"{self.new_url}. Publish to the recorded URL - an account that cannot "
            f"edit it needs edit access shared with it, not a second hub page."
        )


def set_hub_url(hub: PlanHub, url: str) -> bool:
    """
    :param hub: The hub to record the URL in.
    :param url: The hub page's URL.
    :return: Whether the recorded URL changed.
    :raises HubUrlConflictError: When a different URL is already recorded.
    """
    if hub.url == url:
        return False
    if hub.url is not None:
        raise HubUrlConflictError(hub.url, url)
    hub.url = url
    return True


# %% gathering


@dataclass
class NotesBranchReader:
    """
    One listed repository's notes branch, fetched into a scratch repository.
    """

    repository: str
    """
    The repository the branch belongs to.
    """

    scratch: Path
    """
    The scratch repository it was fetched into.
    """

    plans_directory: str = HubDefault.PLANS_DIRECTORY.value
    """
    Where the branch keeps its plans.
    """

    @classmethod
    def fetch(
        cls, repository: str, branch: str, remote_url_template: str, scratch: Path
    ) -> NotesBranchReader | None:
        """
        :return: A reader over the fetched branch, or ``None`` when it cannot be fetched.
        """
        subprocess.run(["git", "init", "--quiet", "--bare", str(scratch)], check=True)
        fetched = subprocess.run(
            [
                "git",
                "-C",
                str(scratch),
                "fetch",
                "--quiet",
                "--depth",
                "1",
                remote_url_template.format(repository=repository),
                branch,
            ],
            capture_output=True,
            text=True,
        )
        if fetched.returncode != 0:
            logger.warning(
                f"{repository}: cannot fetch {branch}: {fetched.stderr.strip()}"
            )
            return None
        return cls(repository, scratch)

    def read(self, relative_path: str) -> str | None:
        """
        :param relative_path: A path inside the plans directory.
        :return: The file's content, or ``None`` when the branch has no such file.
        """
        shown = subprocess.run(
            [
                "git",
                "-C",
                str(self.scratch),
                "show",
                f"FETCH_HEAD:{self.plans_directory}/{relative_path}",
            ],
            capture_output=True,
            text=True,
        )
        return shown.stdout if shown.returncode == 0 else None

    def plan_identifiers(self) -> list[str]:
        """
        :return: Every plan on the branch, in name order.
        """
        listed = subprocess.run(
            [
                "git",
                "-C",
                str(self.scratch),
                "ls-tree",
                "--name-only",
                f"FETCH_HEAD:{self.plans_directory}",
            ],
            capture_output=True,
            text=True,
        )
        return sorted(
            name
            for name in listed.stdout.split()
            if not name.startswith("_") and self.read(f"{name}/plan.yaml") is not None
        )

    def summary(self) -> dict[str, Any]:
        """
        :return: The repository's entry in build_hub.py's input.
        """
        urls = (
            yaml.safe_load(self.read(HubDefault.DASHBOARD_URL_CACHE.value) or "") or {}
        )
        plans = []
        for identifier in self.plan_identifiers():
            plan = yaml.safe_load(self.read(f"{identifier}/plan.yaml"))
            items = plan.get("items") or []
            plans.append(
                {
                    "id": identifier,
                    "title": plan.get("title", identifier),
                    "description": plan.get("description", ""),
                    "done": sum(1 for item in items if item.get("status") == "done"),
                    "total": len(items),
                    "dashboard_url": urls.get(identifier),
                }
            )
        return {
            "repository": self.repository,
            "index_url": urls.get(HubDefault.INDEX_KEY.value),
            "plans": plans,
        }


def gather(hub: PlanHub, remote_url_template: str) -> list[dict[str, Any]]:
    """
    :param hub: The hub whose repositories to read.
    :param remote_url_template: How a repository's name becomes a fetchable URL.
    :return: One entry per repository, unreachable ones with no plans and an ``error``.
    """
    entries = []
    with tempfile.TemporaryDirectory() as scratch_root:
        for position, repository in enumerate(hub.repositories):
            reader = NotesBranchReader.fetch(
                repository,
                hub.notes_branch,
                remote_url_template,
                Path(scratch_root) / str(position),
            )
            if reader is None:
                entries.append(
                    {
                        "repository": repository,
                        "index_url": None,
                        "plans": [],
                        "error": f"cannot fetch {hub.notes_branch}",
                    }
                )
                continue
            entries.append(reader.summary())
    return entries


# %% command


def write_if_changed(hub: PlanHub, changed: bool, output: Path) -> None:
    """
    Write the hub file and print whether it changed.
    """
    output.write_text(hub.to_text())
    logger.info(json.dumps({"changed": changed}))


def main() -> int:
    """
    Parse arguments and run one subcommand. See the module docstring.
    """
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    subcommands = parser.add_subparsers(dest="command", required=True)

    register_parser = subcommands.add_parser("register")
    register_parser.add_argument("--hub", required=True, type=Path)
    register_parser.add_argument("--repository", required=True)
    register_parser.add_argument("--registry", default=None)
    register_parser.add_argument("--output", required=True, type=Path)

    url_parser = subcommands.add_parser("set-url")
    url_parser.add_argument("--hub", required=True, type=Path)
    url_parser.add_argument("--url", required=True)
    url_parser.add_argument("--output", required=True, type=Path)

    gather_parser = subcommands.add_parser("gather")
    gather_parser.add_argument("--hub", required=True, type=Path)
    gather_parser.add_argument("--output", required=True, type=Path)
    gather_parser.add_argument(
        "--remote-url-template", default=HubDefault.REMOTE_URL_TEMPLATE.value
    )

    arguments = parser.parse_args()
    hub = PlanHub.load(arguments.hub)

    if arguments.command == "register":
        created = hub is None
        if created:
            hub = PlanHub(registry=arguments.registry or arguments.repository)
        registered = hub.register(arguments.repository)
        write_if_changed(hub, created or registered, arguments.output)
        return 0

    if hub is None:
        logger.error(f"No hub file at {arguments.hub}; run `register` first.")
        return 1

    if arguments.command == "set-url":
        try:
            changed = set_hub_url(hub, arguments.url)
        except HubUrlConflictError as error:
            logger.error(str(error))
            return 1
        write_if_changed(hub, changed, arguments.output)
        return 0

    arguments.output.write_text(
        json.dumps(gather(hub, arguments.remote_url_template), indent=2)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
