#!/usr/bin/env python3
"""
The plan hub: every repository whose personal-notes branch holds plans, served as one site.

Each repository keeps its own plans. The hub file names the site they are published on,
the registry repository whose copy lists every repository, and that list. Every
registered repository's notes carry a copy, so a session anywhere knows the site and its
own place in it without reading another repository, under any account.

Usage:
    python3 -m basstler.plan_hub register --hub <hub.yaml> --repository <owner/repo> \\
        [--registry <owner/repo>] [--site-url <url>] --output <out>

Adds a repository to the hub file, creating the file (with this repository as its own
registry, unless one is named) when absent. Prints ``{"changed": true|false}``; push the
output only when it changed.
"""

from __future__ import annotations

import argparse
import io
import json
import subprocess
import sys
import tarfile
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
from typing import Any

import yaml

from basstler.standard_streams import StandardStreamHandler

logger = StandardStreamHandler.logger_for(__name__)
"""
This module's logger, which is also what its command prints through.
"""


class HubDefault(Enum):
    """
    The values a hub file falls back to where it names none.
    """

    NOTES_BRANCH = "claude/personal-notes"
    """
    The branch every listed repository keeps its notes on.
    """

    PLANS_DIRECTORY = ".claude/personal/plans"
    """
    Where a notes branch keeps its plans.
    """

    HUB_FILE = "_hub.yaml"
    """
    The hub file, relative to the plans directory.
    """

    REMOTE_URL_TEMPLATE = "https://github.com/{repository}"
    """
    How a listed repository's name becomes a URL git can fetch.
    """


HUB_FILE_HEADER = """\
# The plan hub. Generated by basstler.plan_hub: every listed repository's notes
# carry a copy, and the registry's copy is the one whose list is complete. The
# site is built from every listed repository's plans by basstler.build_site.
"""
"""
The comment every written hub file opens with.
"""


@dataclass
class PlanHub:
    """
    The hub file's content.
    """

    registry: str
    """
    The repository whose notes hold the complete list.
    """

    repositories: list[str] = field(default_factory=list)
    """
    Every repository whose plans the site shows, in the order they are shown.
    """

    site_url: str | None = None
    """
    The address the site is served from, or ``None`` before one was chosen.
    """

    notes_branch: str = HubDefault.NOTES_BRANCH.value
    """
    The branch each listed repository keeps its notes on.
    """

    @classmethod
    def from_mapping(cls, data: dict[str, Any]) -> PlanHub:
        """
        :param data: The parsed hub file.
        :return: The hub it describes.
        """
        return cls(
            registry=data["registry"],
            repositories=list(data.get("repositories") or []),
            site_url=data.get("site_url"),
            notes_branch=data.get("notes_branch") or HubDefault.NOTES_BRANCH.value,
        )

    @classmethod
    def load(cls, path: Path) -> PlanHub | None:
        """
        :param path: The hub file, which may not exist.
        :return: The hub, or ``None`` when the file is absent or empty.
        """
        if not path.is_file():
            return None
        data = yaml.safe_load(path.read_text())
        return cls.from_mapping(data) if data else None

    def to_text(self) -> str:
        """
        :return: The hub file's content, header comment first.
        """
        data = {
            "site_url": self.site_url,
            "registry": self.registry,
            "notes_branch": self.notes_branch,
            "repositories": self.repositories,
        }
        return HUB_FILE_HEADER + yaml.safe_dump(data, sort_keys=False)

    def register(self, repository: str) -> bool:
        """
        :param repository: The repository to list.
        :return: Whether it was not listed before.
        """
        if repository in self.repositories:
            return False
        self.repositories.append(repository)
        return True


@dataclass
class NotesBranch:
    """
    One listed repository's notes branch, fetched into a scratch repository.
    """

    repository: str
    """
    The repository the branch belongs to.
    """

    scratch: Path
    """
    The scratch repository it was fetched into.
    """

    @classmethod
    def fetch(
        cls, repository: str, branch: str, remote_url_template: str, scratch: Path
    ) -> NotesBranch | None:
        """
        :return: The fetched branch, or ``None`` when it cannot be fetched.
        """
        subprocess.run(["git", "init", "--quiet", "--bare", str(scratch)], check=True)
        fetched = subprocess.run(
            [
                "git",
                "-C",
                str(scratch),
                "fetch",
                "--quiet",
                "--depth",
                "1",
                remote_url_template.format(repository=repository),
                branch,
            ],
            capture_output=True,
            text=True,
        )
        if fetched.returncode != 0:
            logger.warning(
                f"{repository}: cannot fetch {branch}: {fetched.stderr.strip()}"
            )
            return None
        return cls(repository, scratch)

    def read(self, relative_path: str) -> str | None:
        """
        :param relative_path: A path inside the plans directory.
        :return: The file's content, or ``None`` when the branch has no such file.
        """
        shown = subprocess.run(
            [
                "git",
                "-C",
                str(self.scratch),
                "show",
                f"FETCH_HEAD:{HubDefault.PLANS_DIRECTORY.value}/{relative_path}",
            ],
            capture_output=True,
            text=True,
        )
        return shown.stdout if shown.returncode == 0 else None

    def export_plans(self, destination: Path) -> Path:
        """
        Write the branch's plans directory out as plain files.

        :param destination: The directory to write it under.
        :return: The written plans directory, empty when the branch has none.
        """
        archived = subprocess.run(
            [
                "git",
                "-C",
                str(self.scratch),
                "archive",
                "FETCH_HEAD",
                HubDefault.PLANS_DIRECTORY.value,
            ],
            capture_output=True,
        )
        if archived.returncode == 0:
            with tarfile.open(fileobj=io.BytesIO(archived.stdout)) as archive:
                archive.extractall(destination, filter="data")
        plans_directory = destination / HubDefault.PLANS_DIRECTORY.value
        plans_directory.mkdir(parents=True, exist_ok=True)
        return plans_directory


def main() -> int:
    """
    Parse arguments and register a repository. See the module docstring.
    """
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    subcommands = parser.add_subparsers(dest="command", required=True)
    register_parser = subcommands.add_parser("register")
    register_parser.add_argument("--hub", required=True, type=Path)
    register_parser.add_argument("--repository", required=True)
    register_parser.add_argument("--registry", default=None)
    register_parser.add_argument("--site-url", default=None)
    register_parser.add_argument("--output", required=True, type=Path)
    arguments = parser.parse_args()

    hub = PlanHub.load(arguments.hub)
    created = hub is None
    if created:
        hub = PlanHub(
            registry=arguments.registry or arguments.repository,
            site_url=arguments.site_url,
        )
    changed = hub.register(arguments.repository) or created
    if arguments.site_url and hub.site_url != arguments.site_url:
        hub.site_url = arguments.site_url
        changed = True
    arguments.output.write_text(hub.to_text())
    logger.info(json.dumps({"changed": changed}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
